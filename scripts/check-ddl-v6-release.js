'use strict';

var assert = require('assert');
var childProcess = require('child_process');
var fs = require('fs');
var os = require('os');
var path = require('path');
var root = path.resolve(__dirname, '..');
var npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
function run(command, args, options) { return childProcess.execFileSync(command, args, Object.assign({ cwd:root, encoding:'utf8', stdio:['ignore','pipe','pipe'] }, options || {})); }

var temp = fs.mkdtempSync(path.join(os.tmpdir(), 'nubloxsql-ddl-v6-'));
var tarball = null;
try {
  tarball = run(npm, ['pack','--silent','--ignore-scripts']).trim().split(/\r?\n/).pop();
  var tarballPath = path.join(root, tarball);
  fs.writeFileSync(path.join(temp,'package.json'), JSON.stringify({name:'nubloxsql-ddl-v6-smoke',private:true}));
  run(npm,['install',tarballPath,'--ignore-scripts','--no-audit','--no-fund'],{cwd:temp});
  var smoke = [
    "const assert=require('assert'); const sql=require('nubloxsql');",
    "for(const id of ['integrity.generatedColumns','integrity.generatedStored','integrity.generatedVirtual','integrity.identity','integrity.identityAlways','integrity.identityByDefault']){const c=sql.capabilityOntology.implementation(id); assert(c&&c.scope==='ddl-v6'&&c.qualified);}",
    "const stored=sql.capabilityModel.transpileSql('postgresql','mysql','CREATE TABLE t (a INTEGER, b INTEGER, total INTEGER GENERATED ALWAYS AS (a + b) STORED)'); assert(stored.certified&&stored.scope==='ddl-v6'&&stored.sql.includes('GENERATED ALWAYS AS'));",
    "const identity=sql.capabilityModel.transpileSql('postgresql','postgresql','CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY)'); assert(identity.certified&&identity.sql.includes('AS IDENTITY'));",
    "let blocked=false; try{sql.capabilityModel.transpileSql('postgresql','mysql','CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY)');}catch(e){blocked=/identity|semantic/i.test(String(e&&e.message));} assert.strictEqual(blocked,true);"
  ].join('\n');
  fs.writeFileSync(path.join(temp,'smoke.js'),smoke); run(process.execPath,['smoke.js'],{cwd:temp});
  run(npm,['install','--no-save','--ignore-scripts','--no-audit','--no-fund','typescript@5.9.3','@types/node@22'],{cwd:temp});
  var ts=[
    "import sql = require('nubloxsql');",
    "import type { SqlStatementAst, SqlAstGeneratedColumn, SqlAstIdentityColumn, SqlCreateTableStatementAst, SqlDdlCompilerScope } from 'nubloxsql';",
    "const a:SqlStatementAst=sql.capabilityModel.parseSql('postgresql','CREATE TABLE t (a INTEGER, b INTEGER, total INTEGER GENERATED ALWAYS AS (a + b) STORED)');",
    "if(a.type==='CreateTableStatement'){const t:SqlCreateTableStatementAst=a; const g:SqlAstGeneratedColumn|undefined=t.columns[2].generated; void g;}",
    "const b:SqlStatementAst=sql.capabilityModel.parseSql('postgresql','CREATE TABLE ids (id BIGINT GENERATED BY DEFAULT AS IDENTITY)');",
    "if(b.type==='CreateTableStatement'){const i:SqlAstIdentityColumn|undefined=b.columns[0].identity; void i;}",
    "const scope:SqlDdlCompilerScope='ddl-v6'; void scope;"
  ].join('\n');
  fs.writeFileSync(path.join(temp,'smoke.ts'),ts); fs.writeFileSync(path.join(temp,'tsconfig.json'),JSON.stringify({compilerOptions:{strict:true,noEmit:true,module:'commonjs',target:'ES2022',moduleResolution:'node',esModuleInterop:true,skipLibCheck:false},files:['smoke.ts']}));
  var tsc=path.join(temp,'node_modules','.bin',process.platform==='win32'?'tsc.cmd':'tsc'); run(tsc,['-p','tsconfig.json'],{cwd:temp});
  console.log('NuBloxSQL packed ddl-v6 release qualification: PASS');
} finally { if(tarball){try{fs.unlinkSync(path.join(root,tarball));}catch(_){}} fs.rmSync(temp,{recursive:true,force:true}); }
