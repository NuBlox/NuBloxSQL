'use strict';

var assert = require('assert');
var sql = require('..');
var model = sql.capabilityModel;

(function postgresSequenceOptions() {
  var ast = model.parseSql('postgresql', 'CREATE SEQUENCE ledger_seq START WITH 10 INCREMENT BY 2 MINVALUE 10 MAXVALUE 100 CACHE 5 CYCLE');
  assert.strictEqual(ast.type, 'CreateSequenceStatement');
  assert.deepStrictEqual(ast.options, { start:10, increment:2, minValue:10, maxValue:100, cache:5, cycle:true });
  var analysis = model.analyzeAst(ast);
  assert.strictEqual(analysis.scope, 'ddl-v11');
  assert.ok(analysis.capabilities.indexOf('schema.sequenceOptions.start') !== -1);
  assert.ok(analysis.capabilities.indexOf('schema.sequenceOptions.cycle') !== -1);
  var compiled = model.compileAst('postgresql', ast);
  assert.ok(/START WITH 10/.test(compiled.sql));
  assert.ok(/INCREMENT BY 2/.test(compiled.sql));
  assert.ok(/CACHE 5/.test(compiled.sql));
})();

(function postgresIdentityOptions() {
  var ast = model.parseSql('postgresql', 'CREATE TABLE identity_test (id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 20 INCREMENT BY 3 CACHE 2 NO CYCLE), note TEXT)');
  assert.strictEqual(ast.columns[0].identity.mode, 'by-default');
  assert.deepStrictEqual(ast.columns[0].identity.options, { start:20, increment:3, cache:2, cycle:false });
  var analysis = model.analyzeAst(ast);
  assert.strictEqual(analysis.scope, 'ddl-v11');
  assert.ok(analysis.capabilities.indexOf('integrity.identitySequenceOptions') !== -1);
  var compiled = model.compileAst('postgresql', ast);
  assert.ok(/GENERATED BY DEFAULT AS IDENTITY \(START WITH 20 INCREMENT BY 3 CACHE 2 NO CYCLE\)/.test(compiled.sql));
})();

(function mysqlAutoIncrement() {
  var ast = model.parseSql('mysql', 'CREATE TABLE mysql_ids (id BIGINT AUTO_INCREMENT PRIMARY KEY, note VARCHAR(20))');
  assert.strictEqual(ast.columns[0].autoIncrement.strategy, 'mysql-auto-increment');
  assert.strictEqual(model.analyzeAst(ast).scope, 'ddl-v11');
  var compiled = model.compileAst('mysql', ast);
  assert.ok(/AUTO_INCREMENT/.test(compiled.sql));
  assert.throws(function () { model.compileAst('postgresql', ast); }, /AUTO_INCREMENT cannot be lowered/);
  assert.throws(function () {
    model.transpileSql('mysql', 'postgresql', 'CREATE TABLE mysql_ids (id BIGINT AUTO_INCREMENT PRIMARY KEY)');
  }, /explicit cross-dialect transformation/);
})();

(function sqliteAutoIncrement() {
  var ast = model.parseSql('sqlite', 'CREATE TABLE sqlite_ids (id INTEGER PRIMARY KEY AUTOINCREMENT, note TEXT)');
  assert.strictEqual(ast.columns[0].autoIncrement.strategy, 'sqlite-rowid-autoincrement');
  var analysis = model.analyzeAst(ast);
  assert.strictEqual(analysis.scope, 'ddl-v11');
  assert.ok(analysis.capabilities.indexOf('integrity.sqliteRowidAutoIncrement') !== -1);
  var compiled = model.compileAst('sqlite', ast);
  assert.ok(/INTEGER PRIMARY KEY AUTOINCREMENT/.test(compiled.sql));
  assert.throws(function () {
    model.parseSql('sqlite', 'CREATE TABLE bad_ids (id BIGINT PRIMARY KEY AUTOINCREMENT)');
  }, /INTEGER PRIMARY KEY/);
})();

(function invalidOptionsFailClosed() {
  assert.throws(function () { model.parseSql('postgresql', 'CREATE SEQUENCE s INCREMENT BY 0'); }, /cannot be zero/);
  assert.throws(function () { model.parseSql('postgresql', 'CREATE SEQUENCE s CACHE 0'); }, /at least 1/);
  assert.throws(function () { model.parseSql('postgresql', 'CREATE SEQUENCE s START WITH 1 START WITH 2'); }, /Duplicate/);
})();

