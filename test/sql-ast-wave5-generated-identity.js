'use strict';

var assert = require('assert');
var sql = require('..');
var model = sql.capabilityModel;
var ontology = sql.capabilityOntology;

(function generatedStoredPortable() {
  var source = 'CREATE TABLE totals (price DECIMAL(10,2), qty INTEGER, total DECIMAL(12,2) GENERATED ALWAYS AS (price * qty) STORED)';
  var ast = model.parseSql('postgresql', source);
  assert.strictEqual(ast.type, 'CreateTableStatement');
  assert.strictEqual(ast.columns[2].generated.storage, 'stored');
  assert.strictEqual(ast.columns[2].generated.expression.type, 'BinaryExpression');
  var analysis = model.analyzeAst(ast);
  assert.strictEqual(analysis.scope, 'ddl-v6');
  assert.ok(analysis.capabilities.indexOf('integrity.generatedColumns') !== -1);
  assert.ok(analysis.capabilities.indexOf('integrity.generatedStored') !== -1);
  var mysql = model.transpileSql('postgresql', 'mysql', source);
  assert.strictEqual(mysql.certified, true);
  assert.strictEqual(mysql.scope, 'ddl-v6');
  assert.ok(/GENERATED ALWAYS AS\\s*\\(/i.test(mysql.sql));
  assert.ok(mysql.sql.indexOf('`price`') !== -1);
  assert.ok(mysql.sql.indexOf('`qty`') !== -1);
  assert.ok(/\\bSTORED\\b/i.test(mysql.sql));
})();

(function sqliteGeneratedRequiresRuntimeEvidence() {
  var source = 'CREATE TABLE totals (price INTEGER, qty INTEGER, total INTEGER GENERATED ALWAYS AS (price * qty) STORED)';
  assert.throws(function () { model.transpileSql('postgresql', 'sqlite', source); }, /runtime qualification/);
  var runtime = model.qualify('sqlite', { version: '3.49.1', source: 'ddl-v6-static-test' });
  var result = model.transpileSql('postgresql', 'sqlite', source, { targetQualification: runtime });
  assert.strictEqual(result.certified, true);
  assert.ok(result.sql.indexOf('GENERATED ALWAYS AS ("price" * "qty") STORED') !== -1);
})();

(function postgresIdentityIsExplicit() {
  var always = model.parseSql('postgresql', 'CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY)');
  assert.strictEqual(always.columns[0].identity.mode, 'always');
  assert.ok(model.analyzeAst(always).capabilities.indexOf('integrity.identityAlways') !== -1);
  assert.strictEqual(model.compileAst('postgresql', always).sql, 'CREATE TABLE "ids" ("id" BIGINT GENERATED ALWAYS AS IDENTITY)');

  var byDefault = model.parseSql('postgresql', 'CREATE TABLE ids (id BIGINT GENERATED BY DEFAULT AS IDENTITY)');
  assert.strictEqual(byDefault.columns[0].identity.mode, 'by-default');
  assert.ok(model.analyzeAst(byDefault).capabilities.indexOf('integrity.identityByDefault') !== -1);

  assert.throws(function () { model.transpileSql('postgresql', 'mysql', 'CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY)'); }, /identity|semantic/i);
  assert.throws(function () { model.parseSql('mysql', 'CREATE TABLE ids (id BIGINT GENERATED ALWAYS AS IDENTITY)'); }, /PostgreSQL source syntax/);
})();

(function postgresVirtualNeeds18Evidence() {
  var source = 'CREATE TABLE totals (price INTEGER, qty INTEGER, total INTEGER GENERATED ALWAYS AS (price * qty) VIRTUAL)';
  assert.throws(function () { model.transpileSql('postgresql', 'postgresql', source); }, /18\+ source runtime qualification/);
  var pg18 = model.qualify('postgresql', { version: '18', source: 'ddl-v6-static-test' });
  var result = model.transpileSql('postgresql', 'postgresql', source, { sourceQualification: pg18, targetQualification: pg18 });
  assert.strictEqual(result.certified, true);
  assert.ok(result.sql.indexOf(' VIRTUAL') !== -1);
  var pg17 = model.qualify('postgresql', { version: '17', source: 'ddl-v6-static-test' });
  assert.throws(function () { model.transpileSql('postgresql', 'postgresql', source, { sourceQualification: pg17, targetQualification: pg17 }); }, /18\+ source runtime qualification/);
})();

(function quotedIdentifierIdentityIsPreserved() {
  var ast = model.parseSql('postgresql', 'CREATE TABLE quoted_names ("A" INTEGER, "a" INTEGER GENERATED ALWAYS AS ("A" + 1) STORED)');
  assert.strictEqual(ast.columns[0].name.parts[0], 'A');
  assert.strictEqual(ast.columns[0].generated, undefined);
  assert.strictEqual(ast.columns[1].name.parts[0], 'a');
  assert.strictEqual(ast.columns[1].generated.storage, 'stored');
})();
(function validationAndOntology() {
  assert.throws(function () { model.parseSql('postgresql', 'CREATE TABLE x (a INTEGER GENERATED ALWAYS AS (1) STORED DEFAULT 1)'); }, /final ddl-v6 column clause/);
  ['integrity.generatedColumns','integrity.generatedStored','integrity.generatedVirtual','integrity.identity','integrity.identityAlways','integrity.identityByDefault'].forEach(function (path) {
    var coverage = ontology.implementation(path);
    assert.ok(coverage, path);
    assert.strictEqual(coverage.scope, 'ddl-v6');
    assert.strictEqual(coverage.qualified, true);
  });
})();

